const assert=require('node:assert/strict');
const {taskView}=require('../labagent/web/task-status.js');
const session={status:'running',step:0,steps:[{gate:'meter_setup',instruction:'选择实际档位'}],
 interaction:{phase:'observing',message:'请让旋钮入镜',primary_action:null}};
const automatic={autoEnabled:true};
assert.equal(taskView(session,automatic).primary_action,null);
assert.equal(taskView(session,{autoEnabled:false}).primary_action.kind,'confirm_step');
assert.equal(taskView(session,{...automatic,busy:'planning'}).phase,'planning');
assert.equal(taskView(session,{...automatic,hidden:true}).phase,'background');
assert.equal(taskView(session,{...automatic,error:'相机权限拒绝'}).primary_action.kind,'retry');
assert.equal(taskView(session,{...automatic,disconnected:true}).phase,'error');
assert.equal(taskView(session,{...automatic,manualEdits:true}).primary_action.kind,'confirm_equipment');
const paused={...session,status:'paused',interaction:{phase:'paused',message:'已暂停',primary_action:{kind:'resume'}}};
assert.equal(taskView(paused,{...automatic,busy:'observing',error:'过时的错误'}).primary_action.kind,'resume');
const completed={...session,status:'completed',interaction:{phase:'completed',primary_action:{kind:'show_results'}}};
assert.equal(taskView(completed,{...automatic,busy:'planning'}).phase,'completed');
const manualStep={...session,interaction:{phase:'waiting_user',message:'请完成实际操作',primary_action:{kind:'confirm_step'}}};
assert.equal(taskView(manualStep,automatic).primary_action.kind,'confirm_step');
const measurement={...session,steps:[{gate:'measurement',instruction:'核对读数'}]};
assert.equal(taskView(measurement,{autoEnabled:false,candidate:true}).primary_action.kind,'confirm_candidate');
assert.equal(taskView(measurement,{autoEnabled:false,candidate:false}).primary_action.kind,'manual_measurement');
assert.equal(taskView(session,{...automatic,replayBlocked:true}).primary_action.label,'开始自动演练');
const advancing={...session,interaction:{phase:'advancing',message:'已通过',primary_action:{kind:'advance'}}};
assert.equal(taskView(advancing,automatic).primary_action,null);
assert.equal(taskView(advancing,{autoEnabled:false}).primary_action.kind,'advance');
const meter={...automatic,meterStep:true,meterTried:false,meterMessage:'首次自动检查一次'};
assert.equal(taskView(session,meter).primary_action,null);
assert.equal(taskView(session,{...meter,meterTried:true}).primary_action.kind,'inspect_meter');
assert.equal(taskView(session,{...meter,meterTried:true}).primary_action.label,'重新检测仪表设置');
assert.equal(taskView(session,{...meter,meterTried:true,busy:'observing'}).primary_action,null);
assert.equal(taskView(paused,{...meter,meterTried:true}).primary_action.kind,'resume');
assert.equal(taskView(session,{...meter,meterTried:true,autoEnabled:false}).primary_action.kind,'confirm_step');
const notice={...session,steps:[{gate:'save',instruction:'保存'}],interaction:{phase:'notice',message:'请移开表笔并关闭万用表',primary_action:null}};
assert.equal(taskView(notice,automatic).phase,'notice');
assert.equal(taskView(notice,{autoEnabled:false}).primary_action,null);
console.log('PASS: canonical task state, reminder without confirmation, one action, pause/completion precedence, camera error, background, manual fallback, replay and auto advance');
